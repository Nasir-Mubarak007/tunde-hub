/**
 * The listing entity and its lifecycle.
 * Every invariant lives here in pure functions.
 * Storage lives in infrastructure, which implements the ports in repositories.
 */
import type { Result } from "./result";
import { err, ok } from "./result";
import type { ListingStatus } from "./listingStatus";
import { canTransitionListingStatus } from "./listingStatus";
import type { Platform } from "./platform";
import { isPlatform } from "./platform";

/** Currency codes are three uppercase letters. NGN is the default at the database. */
const CURRENCY_PATTERN = /^[A-Z]{3}$/;

/** Slugs are lowercase groups joined by single separators. */
const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** One listed account. Claim fields name the buyer holding a pending claim. */
export interface Listing {
  readonly id: number;
  readonly slug: string;
  readonly title: string;
  readonly description: string | null;
  readonly platform: Platform;
  readonly priceAmount: number;
  readonly currency: string;
  readonly followerCount: number;
  readonly accountAgeMonths: number;
  readonly status: ListingStatus;
  readonly claimedByUserId: string | null;
  readonly claimToken: string | null;
  readonly pendingSince: Date | null;
  readonly soldAt: Date | null;
  readonly deletedAt: Date | null;
  readonly createdAt: Date;
  readonly updatedAt: Date;
}

/** A listing before the database assigns an id. */
export type NewListing = Omit<Listing, "id">;

/** Plain input for creating a listing. Status is always available, never an input. */
export interface CreateListingInput {
  readonly slug: string;
  readonly title: string;
  readonly description: string | null;
  readonly platform: string;
  readonly priceAmount: number;
  readonly currency: string;
  readonly followerCount: number;
  readonly accountAgeMonths: number;
}

/** Fields the owner may change. The slug is frozen and never appears here. */
export interface UpdateListingChanges {
  readonly title?: string;
  readonly description?: string | null;
  readonly platform?: string;
  readonly priceAmount?: number;
  readonly currency?: string;
  readonly followerCount?: number;
  readonly accountAgeMonths?: number;
}

/** Why listing values are invalid. Returned as values, never thrown. */
export type ListingValidationIssue =
  | "title-required"
  | "slug-required"
  | "slug-invalid"
  | "platform-unknown"
  | "price-invalid"
  | "currency-invalid"
  | "follower-count-invalid"
  | "account-age-invalid";

/** Why a lifecycle move is refused. Returned as a value, never thrown. */
export type ListingTransitionError = "listing-deleted" | "not-available" | "not-pending" | "not-sold";

/** Input for a claim write. The token is generated by the caller, never by the client. */
export interface ClaimInput {
  readonly buyerId: string;
  readonly token: string;
  readonly now: Date;
}

/** Validates the shared scalar fields. Takes the fields, returns the distinct issues. */
function validateScalarFields(fields: {
  readonly title: string;
  readonly platform: string;
  readonly priceAmount: number;
  readonly currency: string;
  readonly followerCount: number;
  readonly accountAgeMonths: number;
}): ListingValidationIssue[] {
  const issues: ListingValidationIssue[] = [];
  if (fields.title.trim().length === 0) {
    issues.push("title-required");
  }
  if (!isPlatform(fields.platform)) {
    issues.push("platform-unknown");
  }
  if (!Number.isInteger(fields.priceAmount) || fields.priceAmount < 0) {
    issues.push("price-invalid");
  }
  if (!CURRENCY_PATTERN.test(fields.currency)) {
    issues.push("currency-invalid");
  }
  if (!Number.isInteger(fields.followerCount) || fields.followerCount < 0) {
    issues.push("follower-count-invalid");
  }
  if (!Number.isInteger(fields.accountAgeMonths) || fields.accountAgeMonths < 0) {
    issues.push("account-age-invalid");
  }
  return issues;
}

/** Creates a listing entity. Takes plain input plus the clock reading, returns the entity or the issues. */
export function createListing(
  input: CreateListingInput,
  now: Date,
): Result<NewListing, readonly ListingValidationIssue[]> {
  const issues = validateScalarFields(input);
  if (input.slug.trim().length === 0) {
    issues.push("slug-required");
  } else if (!SLUG_PATTERN.test(input.slug)) {
    issues.push("slug-invalid");
  }
  if (issues.length > 0) {
    return err(issues);
  }
  return ok({
    slug: input.slug,
    title: input.title.trim(),
    description: input.description,
    platform: input.platform as Platform,
    priceAmount: input.priceAmount,
    currency: input.currency,
    followerCount: input.followerCount,
    accountAgeMonths: input.accountAgeMonths,
    status: "available",
    claimedByUserId: null,
    claimToken: null,
    pendingSince: null,
    soldAt: null,
    deletedAt: null,
    createdAt: now,
    updatedAt: now,
  });
}

/** Updates editable fields. Takes the listing plus the changes, returns the updated copy or the issues. */
export function updateListingDetails(
  listing: Listing,
  changes: UpdateListingChanges,
  now: Date,
): Result<Listing, readonly ListingValidationIssue[]> {
  const next = {
    title: changes.title ?? listing.title,
    platform: changes.platform ?? listing.platform,
    priceAmount: changes.priceAmount ?? listing.priceAmount,
    currency: changes.currency ?? listing.currency,
    followerCount: changes.followerCount ?? listing.followerCount,
    accountAgeMonths: changes.accountAgeMonths ?? listing.accountAgeMonths,
  };
  const issues = validateScalarFields(next);
  if (issues.length > 0) {
    return err(issues);
  }
  return ok({
    ...listing,
    title: next.title.trim(),
    description: changes.description === undefined ? listing.description : changes.description,
    platform: next.platform as Platform,
    priceAmount: next.priceAmount,
    currency: next.currency,
    followerCount: next.followerCount,
    accountAgeMonths: next.accountAgeMonths,
    updatedAt: now,
  });
}

/** Claims an available listing. Takes the listing plus the buyer facts, returns the pending copy or the reason. */
export function requestClaim(listing: Listing, input: ClaimInput): Result<Listing, ListingTransitionError> {
  if (listing.deletedAt !== null) {
    return err("listing-deleted");
  }
  if (listing.status !== "available" || !canTransitionListingStatus(listing.status, "pending")) {
    return err("not-available");
  }
  return ok({
    ...listing,
    status: "pending",
    claimedByUserId: input.buyerId,
    claimToken: input.token,
    pendingSince: input.now,
    updatedAt: input.now,
  });
}

/**
 * Releases a pending claim back to available. Takes the listing plus the clock,
 * returns the available copy or the reason. Clears the holder, the token and
 * the pending since stamp.
 */
export function releaseClaim(listing: Listing, now: Date): Result<Listing, ListingTransitionError> {
  if (listing.deletedAt !== null) {
    return err("listing-deleted");
  }
  if (listing.status !== "pending" || !canTransitionListingStatus(listing.status, "available")) {
    return err("not-pending");
  }
  return ok({
    ...listing,
    status: "available",
    claimedByUserId: null,
    claimToken: null,
    pendingSince: null,
    updatedAt: now,
  });
}

/**
 * Confirms a sale on a pending listing. Takes the listing plus the clock,
 * returns the sold copy or the reason. The holder, the token and the pending
 * since stamp all stay on the row.
 */
export function confirmSold(listing: Listing, now: Date): Result<Listing, ListingTransitionError> {
  if (listing.deletedAt !== null) {
    return err("listing-deleted");
  }
  if (listing.status !== "pending" || !canTransitionListingStatus(listing.status, "sold")) {
    return err("not-pending");
  }
  return ok({
    ...listing,
    status: "sold",
    soldAt: now,
    updatedAt: now,
  });
}

/**
 * Sells an available listing straight to sold, for a deal agreed off the site.
 * Takes the listing plus the clock, returns the sold copy or the reason. No
 * holder is named, so the claim columns stay empty.
 */
export function markSoldDirect(listing: Listing, now: Date): Result<Listing, ListingTransitionError> {
  if (listing.deletedAt !== null) {
    return err("listing-deleted");
  }
  if (listing.status !== "available" || !canTransitionListingStatus(listing.status, "sold")) {
    return err("not-available");
  }
  return ok({
    ...listing,
    status: "sold",
    soldAt: now,
    updatedAt: now,
  });
}

/**
 * Reopens a sold listing back to available, for a sale the owner called off.
 * Takes the listing plus the clock, returns the available copy or the reason.
 * Clears the sold stamp plus the holder, the token and the pending since stamp.
 */
export function reopenSold(listing: Listing, now: Date): Result<Listing, ListingTransitionError> {
  if (listing.deletedAt !== null) {
    return err("listing-deleted");
  }
  if (listing.status !== "sold" || !canTransitionListingStatus(listing.status, "available")) {
    return err("not-sold");
  }
  return ok({
    ...listing,
    status: "available",
    soldAt: null,
    claimedByUserId: null,
    claimToken: null,
    pendingSince: null,
    updatedAt: now,
  });
}

/** Soft deletes a listing. Takes the listing plus the clock, returns the deleted copy. Idempotent. */
export function softDeleteListing(listing: Listing, now: Date): Listing {
  if (listing.deletedAt !== null) {
    return listing;
  }
  return { ...listing, deletedAt: now, updatedAt: now };
}

/** Restores a soft deleted listing. Takes the listing plus the clock, returns the restored copy. */
export function restoreListing(listing: Listing, now: Date): Listing {
  return { ...listing, deletedAt: null, updatedAt: now };
}

/** Tells whether a listing is soft deleted. Takes the listing, returns the answer. */
export function isListingDeleted(listing: Listing): boolean {
  return listing.deletedAt !== null;
}

/** Shows age as years and months. Takes total months, returns the display text. */
export function formatAccountAge(totalMonths: number): string {
  const years = Math.floor(totalMonths / 12);
  const months = totalMonths % 12;
  if (years === 0) {
    return `${months}m`;
  }
  if (months === 0) {
    return `${years}y`;
  }
  return `${years}y ${months}m`;
}

/** Shows a whole amount in its currency. Takes the amount plus the code, returns the display text. */
export function formatListingPrice(amount: number, currency: string): string {
  return new Intl.NumberFormat("en-NG", {
    style: "currency",
    currency,
    maximumFractionDigits: 0,
  }).format(amount);
}
