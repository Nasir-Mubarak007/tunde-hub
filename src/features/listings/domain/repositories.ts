/**
 * Repository ports the use cases call.
 * Infrastructure implements these interfaces. Dependency inversion:
 * the domain declares the shape, the database layer fulfils it.
 * Unexpected storage failures throw. Expected domain refusals stay values.
 */
import type { Result } from "./result";
import type { Listing, NewListing } from "./listing";
import type { ListingStatus } from "./listingStatus";
import type { ListingImage } from "./listingImage";
import type { Platform } from "./platform";

/** Rows for replacing a listing screenshots. Plain values, no ids yet. */
export interface ListingImageRow {
  readonly position: number;
  readonly width: number;
  readonly url: string;
  readonly fileKey: string | null;
}

/** Listing writes plus point reads. Implemented by the Drizzle repositories. */
export interface ListingRepository {
  /** Finds by id. Takes the id, returns the listing or null. */
  findById(id: number): Promise<Listing | null>;
  /** Finds by slug. Takes the slug, returns the listing or null. */
  findBySlug(slug: string): Promise<Listing | null>;
  /** Inserts a new row. Takes the entity without id, returns the saved row or slug taken. */
  insertListing(listing: NewListing): Promise<Result<Listing, "slug-taken">>;
  /** Saves changes to an existing row. Takes the entity, returns the saved row. */
  saveListing(listing: Listing): Promise<Listing>;
  /** Removes the row for good. Takes the id, returns nothing. Image rows cascade. */
  removeById(id: number): Promise<void>;
}

/** Screenshot storage behind a listing. Implemented by the Drizzle repositories. */
export interface ListingImageStore {
  /** Lists variants for a listing. Takes the listing id, returns the rows. */
  listForListing(listingId: number): Promise<readonly ListingImage[]>;
  /** Replaces every variant for a listing. Takes the id plus the new rows, returns nothing. */
  replaceForListing(listingId: number, images: readonly ListingImageRow[]): Promise<void>;
  /** Removes every variant for a listing. Takes the id, returns nothing. */
  removeForListing(listingId: number): Promise<void>;
}

/** One click to record alongside a claim, or null when no click is counted. */
export interface ClaimClick {
  readonly visitorHash: string;
  readonly bucket: Date;
}

/** Outcome of one atomic claim attempt. Models the conditional update result. */
export type ClaimAttemptResult =
  | { readonly outcome: "claimed"; readonly listing: Listing; readonly clickCount: number }
  | { readonly outcome: "taken"; readonly clickCount: number }
  | { readonly outcome: "buyer-capped"; readonly clickCount: number }
  | { readonly outcome: "rate-limited"; readonly clickCount: number };

/** Input for one atomic claim attempt. The token is generated by the caller. */
export interface ClaimAttemptInput {
  readonly listingId: number;
  readonly buyerId: string;
  readonly token: string;
  readonly now: Date;
  readonly click: ClaimClick | null;
}

/**
 * Atomic claim writes. The implementation runs one conditional update
 * that only fires while the row is still available, so two simultaneous
 * clicks cannot both succeed. Zero rows means taken. The one pending
 * cap arrives through the partial unique index. The click count is
 * written in the same transaction, so a refused claim still counts.
 */
export interface ClaimStore {
  /** Attempts the claim. Takes the attempt facts, returns the outcome. */
  attemptClaim(input: ClaimAttemptInput): Promise<ClaimAttemptResult>;
}

/**
 * The owner moves over an existing listing row. Every method is one
 * conditional update naming the state the row must still be in, so a
 * stale press that races another press writes nothing and reads back
 * null instead. Timestamps come from the database clock, never from a
 * caller, and every move refuses a soft deleted row.
 */
export interface ListingSaleStore {
  /** Confirms a pending listing as sold, keeping the holder. Takes the id, returns the row or null. */
  confirmSold(listingId: number): Promise<Listing | null>;
  /** Sells an available listing straight to sold. Takes the id, returns the row or null. */
  markSoldDirect(listingId: number): Promise<Listing | null>;
  /** Releases a pending listing back to available. Takes the id, returns the row or null. */
  releaseClaim(listingId: number): Promise<Listing | null>;
  /** Reopens a sold listing back to available. Takes the id, returns the row or null. */
  reopenSold(listingId: number): Promise<Listing | null>;
}

/** One recorded lifecycle move: the listing, where it came from, where it went, and who pressed. */
export interface TransitionLogEntry {
  readonly listingId: number;
  readonly from: ListingStatus;
  readonly to: ListingStatus;
  readonly actorId: string;
}

/**
 * Where lifecycle moves are recorded. A log failure must never block a
 * write that already reached the database, so the implementation never
 * throws and the use case calls it after the write, not before.
 */
export interface TransitionLog {
  /** Records one move. Takes the entry, returns nothing. Never throws. */
  write(entry: TransitionLogEntry): void;
}

/** Hour bucket counters for public writes. Implemented over the clicks table. */
export interface RateLimitStore {
  /** Increments the bucket and returns the new count. Takes the hash plus the bucket, returns the count. */
  incrementAndGetCount(visitorHash: string, bucket: Date): Promise<number>;
  /** Removes rows older than the cutoff. Takes the cutoff, returns the removed row count. */
  pruneOlderThan(cutoff: Date): Promise<number>;
}

/** Sort orders for the public card list. Newest first is the default. */
export type AvailableSort = "newest" | "price" | "followers" | "age";

/** Sort direction. Applies to every sort order. */
export type SortDirection = "asc" | "desc";

/** Parsed keyset cursor. The sort key is a date for newest, a number otherwise. */
export interface AvailableCursor {
  readonly sortKey: Date | number;
  readonly id: number;
}

/** Filters plus paging for the public card list. The sold cutoff marks the sold window edge. */
export interface AvailableListingsQuery {
  readonly platforms: readonly Platform[];
  readonly maxPrice: number | null;
  readonly minFollowers: number | null;
  readonly sort: AvailableSort;
  readonly direction: SortDirection;
  readonly cursor: AvailableCursor | null;
  readonly limit: number;
  readonly soldCutoff: Date;
}

/** One card row. The listing plus its cover image url, when one exists. */
export interface ListingCardRow {
  readonly listing: Listing;
  readonly coverImageUrl: string | null;
}

/** Public card reads. Implemented by the Drizzle repositories. */
export interface ListingQuery {
  /** Lists visible cards. Takes the query, returns at most limit rows in sort order. */
  listAvailableCards(query: AvailableListingsQuery): Promise<readonly ListingCardRow[]>;
  /** Tells whether a buyer already holds a pending listing. Takes the buyer id, returns the answer. */
  hasPendingClaimFor(buyerId: string): Promise<boolean>;
}

/** Who holds a pending listing, as the panel shows it. Plain values, no user entity. */
export interface ClaimHolder {
  readonly userId: string;
  readonly displayName: string | null;
  readonly email: string;
}

/** One admin row. The listing plus who holds it, when somebody does. */
export interface AdminListingRow {
  readonly listing: Listing;
  readonly holder: ClaimHolder | null;
  readonly imageCount: number;
}

/** Paging for the admin list. Newest first, keyset on created_at and id like the public list. */
export interface AdminListingsQuery {
  readonly cursor: AvailableCursor | null;
  readonly limit: number;
  readonly status: AdminStatusFilter;
}

/** One status bucket the panel can filter by. Deleted is a flag, not a lifecycle state. */
export type AdminStatusFilter = "all" | "available" | "pending" | "sold" | "deleted";

/** Every filter the panel offers, in display order. Takes nothing, used for tabs and validation. */
export const ADMIN_STATUS_FILTERS: readonly AdminStatusFilter[] = ["all", "available", "pending", "sold", "deleted"];

/** Checks a raw string. Takes the candidate, returns true only for a known panel filter. */
export function isAdminStatusFilter(value: string): value is AdminStatusFilter {
  return (ADMIN_STATUS_FILTERS as readonly string[]).includes(value);
}

/** One overview count block for the panel. Plain numbers, never entities. */
export interface AdminCounts {
  readonly total: number;
  readonly available: number;
  readonly pending: number;
  readonly sold: number;
  readonly deleted: number;
}

/**
 * Admin reads. Every listing including soft deleted ones, so the panel can
 * restore and purge. The owner role never reaches this port without the
 * caller having checked the session first.
 */
export interface AdminListingQuery {
  /** Lists every listing newest first. Takes the query, returns at most limit rows. */
  listAllForAdmin(query: AdminListingsQuery): Promise<readonly AdminListingRow[]>;
  /** Counts listings per bucket. Takes nothing, returns one count per panel bucket. */
  countForAdmin(): Promise<AdminCounts>;
}

/**
 * Stored file deletion. Implemented over UploadThing. A failure throws so
 * the caller can log it and carry on: the database rows still go.
 */
export interface FileStore {
  /** Deletes stored files by their keys. Takes the keys, returns nothing. Throws when the provider refuses. */
  deleteFiles(fileKeys: readonly string[]): Promise<void>;
}
